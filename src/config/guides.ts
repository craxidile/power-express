import { Locale } from '../models/_commons/localized';
import guidesData from './guides.json';

export interface GuideSection {
  heading: string;
  body: string[];
  bullets?: string[];
}

export interface GuideText {
  title: string;
  description: string;
  intro: string;
  sections: GuideSection[];
  faq: { q: string; a: string }[];
  cta: string;
}

export interface Guide {
  slug: string;
  /** URL path without the locale prefix, e.g. "solar-ppa" or "industries/hotels". */
  path: string;
  kind: 'guide' | 'info' | 'industry' | 'area';
  /** Keywords used to list related projects (area pages). */
  match?: string[];
  /** ISO date of first publication (articles). */
  published?: string;
  text: { [key in Locale]: GuideText };
}

// Copy lives in guides.json (generated by scripts/gen-content-pages.js) so the
// build-time prerender script can use it too.
// DRAFT: general educational content only; no savings percentages, prices or project numbers.
export const guides: Guide[] = guidesData as Guide[];

export const findGuideByPath = (p?: string) =>
  guides.find((g) => g.path === (p ?? '').replace(/\/+$/, ''));
